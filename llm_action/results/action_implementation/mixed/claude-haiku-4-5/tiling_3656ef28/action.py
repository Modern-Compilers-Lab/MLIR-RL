from llm_action.src.actions.base import ActionBase
from llm_action.src.utils.transformation import run_transform_code
import re

class Action(ActionBase):
    """
    Tiling transformation: partitions loop nests into smaller blocks
    to improve cache locality by ensuring intermediate results fit in L1/L2.
    
    This action applies transform.structured.tile_using_for to the tagged
    operation (operation_0) with the specified tile sizes.
    """

    @classmethod
    def parameters(cls) -> dict:
        """
        Define the action's tunable parameters.
        
        Returns:
            dict with single key "tile_sizes": list of non-negative integers
        """
        return {
            "tile_sizes": {
                "description": "List of tile sizes (non-negative integers). "
                               "Non-zero value enables tiling; 0 disables for that dimension.",
                "type": "list[int]",
                "default": None,  # Required parameter
            }
        }

    @classmethod
    def precondition(cls, code: str, params: dict) -> bool:
        """
        Check if the action is applicable to the given IR.
        
        Verifies:
        - The code contains the target operation tag "operation_0"
        - tile_sizes is a non-empty list
        - At least one tile size is non-zero (to avoid trivial no-ops)
        
        Args:
            code: MLIR code as string
            params: Dictionary containing "tile_sizes" key
            
        Returns:
            bool: True if action is applicable, False otherwise
        """
        # Check that operation_0 tag exists
        if 'tag = "operation_0"' not in code:
            return False
        
        # Validate tile_sizes parameter
        if "tile_sizes" not in params:
            return False
        
        tile_sizes = params["tile_sizes"]
        
        # Check that tile_sizes is a list
        if not isinstance(tile_sizes, list):
            return False
        
        # Check that list is non-empty
        if len(tile_sizes) == 0:
            return False
        
        # Check that all elements are non-negative integers
        if not all(isinstance(s, int) and s >= 0 for s in tile_sizes):
            return False
        
        # Check that at least one tile size is non-zero (avoid no-op)
        if all(s == 0 for s in tile_sizes):
            return False
        
        return True

    @classmethod
    def preprocess(cls, code: str, params: dict) -> str:
        """
        Optional preprocessing step. For tiling, no special preparation is needed.
        
        Args:
            code: MLIR code as string
            params: Dictionary containing "tile_sizes" key
            
        Returns:
            str: Preprocessed MLIR code (identity for tiling)
        """
        # No preprocessing needed for tiling
        return code

    @classmethod
    def implement(cls, code: str, params: dict) -> str:
        """
        Apply the tiling transformation using MLIR Transform dialect.
        
        Constructs a transform sequence that:
        1. Matches the target operation via tag "operation_0"
        2. Applies transform.structured.tile_using_for with the given tile_sizes
        3. Handles multi-level tiling automatically
        
        Args:
            code: MLIR code as string
            params: Dictionary containing "tile_sizes" key
            
        Returns:
            str: Transformed MLIR code after tiling
        """
        tile_sizes = params["tile_sizes"]
        
        # Number of loops generated by tiling
        num_loops = len(tile_sizes)
        
        # Build the list of output loop types for transform result
        loop_types = ", ".join(["!transform.any_op"] * num_loops)
        
        # Construct the transform sequence
        transform_code = f"""module attributes {{transform.with_named_sequence}} {{
  transform.named_sequence @__transform_main(%arg0: !transform.any_op {{transform.readonly}}) {{
    %op_0 = transform.structured.match attributes{{tag = "operation_0"}} in %arg0 : (!transform.any_op) -> !transform.any_op
    %tiled_op_0, %tile_loops:{num_loops} = transform.structured.tile_using_for %op_0 tile_sizes {tile_sizes} : (!transform.any_op) -> (!transform.any_op, {loop_types})
    transform.yield
  }}
}}
"""
        
        # Execute the transform
        try:
            transformed = run_transform_code(code, transform_code)
            return transformed
        except Exception:
            # If transform fails, return original code
            # (postcondition will detect this)
            return code

    @classmethod
    def postcondition(cls, before: str, after: str, params: dict) -> bool:
        """
        Verify that the transformation was successful.
        
        Checks:
        - The transformed code differs from the original (not a no-op)
        - The transformed code is non-empty
        - The transformed code still contains valid MLIR structure
        
        Args:
            before: Original MLIR code
            after: Transformed MLIR code
            params: Dictionary containing "tile_sizes" key (not used here)
            
        Returns:
            bool: True if transformation succeeded, False otherwise
        """
        # Reject if code is identical (silent no-op)
        if before.strip() == after.strip():
            return False
        
        # Check that transformed code is non-empty
        if not after or not after.strip():
            return False
        
        # Basic sanity check: must still contain module and func
        if "module" not in after or "func.func" not in after:
            return False
        
        # Must contain some loop-related constructs (scf.for, affine.for, or remain as linalg)
        # Acceptable outcomes:
        # - Contains scf.for (explicit loop nesting introduced by tiling)
        # - Contains affine.for (affine dialect loops)
        # - Still contains linalg (for edge cases where tiling didn't lower)
        has_loops = "scf.for" in after or "affine.for" in after
        has_linalg = "linalg." in after
        
        if not (has_loops or has_linalg):
            return False
        
        return True